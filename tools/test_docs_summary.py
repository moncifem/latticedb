class DocsSummaryTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name).resolve()
        fixture(self.root)

    def tearDown(self):
        self._tmp.cleanup()

    def stage(self):
        out = self.root / "target" / "docs-src"
        return out, ds.stage(self.root, out)

    def test_section_order_and_titles(self):
        out, errors = self.stage()
        self.assertEqual(errors, [])
        lines = (out / "SUMMARY.md").read_text().splitlines()
        parts = [l[2:] for l in lines if l.startswith("# ") and l != "# Summary"]
        self.assertEqual(parts, [t for t, _ in ds.SECTIONS])
        entries = [l for l in lines if l.startswith("- [")]
        self.assertEqual(entries[0], "- [Overview](overview.md)")
        self.assertEqual(entries[1], "- [Glossary](glossary.md)")

    def test_numeric_and_pinned_order(self):
        out, _ = self.stage()
        text = (out / "SUMMARY.md").read_text()
        order = [text.index(s) for s in ("spec/README.md", "spec/2-a.md", "spec/10-b.md", "spec/direction.md")]
        self.assertEqual(order, sorted(order))
        gates = [text.index(s) for s in ("gates/phase-1.md", "gates/phase-1-review.md", "gates/phase-2.md")]
        self.assertEqual(gates, sorted(gates))
        self.assertLess(text.index("ARCHITECTURE.md"), text.index("ENGINEERING.md"))

    def test_excludes_site_generated_corpus_and_summary(self):
        out, _ = self.stage()
        text = (out / "SUMMARY.md").read_text()
        for name in ("site/", "gen.md", "corpus"):
            self.assertNotIn(name, text)
        self.assertFalse((out / "site").exists())
        self.assertTrue((out / "assets" / "b.png").exists())

    def test_deterministic(self):
        out, _ = self.stage()
        first = (out / "SUMMARY.md").read_text()
        out, _ = self.stage()
        self.assertEqual(first, (out / "SUMMARY.md").read_text())

    def test_link_rewriting(self):
        out, errors = self.stage()
        self.assertEqual(errors, [])
        overview = (out / "overview.md").read_text()
        self.assertIn("(ARCHITECTURE.md)", overview)
        self.assertIn(f"({ds.REPO_URL}/blob/main/crates/x/README.md)", overview)
        self.assertIn(f"({ds.REPO_URL}/tree/main/docs/gates)", overview)
        self.assertIn("(assets/b.png)", overview)
        arch = (out / "ARCHITECTURE.md").read_text()
        self.assertIn("(formats/hlc.md)", arch)
        self.assertIn("(glossary.md#wal)", arch)

    def test_broken_link_fails(self):
        write(self.root, "docs/guide.md", "# Guide\n\n[nope](missing.md) and [ok](roadmap.md)\n")
        _, errors = self.stage()
        self.assertEqual(len(errors), 1)
        self.assertIn("docs/guide.md", errors[0])
        self.assertIn("missing.md", errors[0])

    def test_link_to_excluded_build_output_is_broken_only_if_absent(self):
        write(self.root, "docs/guide.md", "# Guide\n\n[x](site/old.md) [y](site/none.md)\n")
        _, errors = self.stage()
        self.assertEqual(len(errors), 1)
        self.assertIn("none.md", errors[0])

    def test_code_is_not_checked(self):
        write(self.root, "docs/guide.md", "# Guide\n\n`[a](nope.md)`\n\n```\n[b](nope2.md)\n```\n")
        _, errors = self.stage()
        self.assertEqual(errors, [])

    def test_external_and_fragment_links_are_left_alone(self):
        write(self.root, "docs/guide.md", "# Guide\n\n[a](https://example.com/x) [b](#top) [c](mailto:a@b.c)\n")
        out, errors = self.stage()
        self.assertEqual(errors, [])
        self.assertIn("(https://example.com/x)", (out / "guide.md").read_text())

    def test_reference_definition_and_attribute(self):
        write(self.root, "docs/guide.md", "# Guide\n\n[r][1]\n\n[1]: nope.md\n\n<a href=\"gone.md\">x</a>\n")
        _, errors = self.stage()
        self.assertEqual(len(errors), 2)

    def test_link_leaving_repository_fails(self):
        write(self.root, "docs/guide.md", "# Guide\n\n[x](../../etc/passwd)\n")
        _, errors = self.stage()
        self.assertEqual(len(errors), 1)

    def test_refuses_staging_outside_root(self):
        with tempfile.TemporaryDirectory() as other:
            errors = ds.stage(self.root, Path(other))
        self.assertEqual(len(errors), 1)
        self.assertIn("refusing", errors[0])

    def test_main_exit_codes(self):
        self.assertEqual(ds.main(["--root", str(self.root), "--out", "target/o"]), 0)
        write(self.root, "docs/guide.md", "# Guide\n\n[x](missing.md)\n")
        self.assertEqual(ds.main(["--root", str(self.root), "--out", "target/o"]), 1)

    def test_natural_key(self):
        names = ["10-a.md", "2-a.md", "README.md", "Z.md", "b.md"]
        self.assertEqual(sorted(names, key=ds.natural_key), ["2-a.md", "10-a.md", "b.md", "README.md", "Z.md"])


if __name__ == "__main__":
    unittest.main()
