#!/usr/bin/env python3
"""Fail when an ignored test is neither run by a workflow nor listed with a reason.

An ignored test never runs in `cargo test`, so a volume test that no workflow starts with `--ignored`
is dead code that reads like evidence (#455). Every attribute under crates/ and xtask/ that contains
the word `ignore` (`#[ignore]`, `#[ignore = "..."]`, `#[cfg_attr(..., ignore)]`, raw-string reasons,
attributes over several lines) marks an ignored test, which must be one of:

- a pending specification: the reason starts with `phase N:` and N is in `pending_phases` in
  tools/ignored-tests.toml (a phase that is still ahead; remove a phase from the list when it starts);
- run by a workflow: a non-comment line of a workflow that can run unattended contains `--ignored` and
  either the test function name, or `--test <file stem>` for the test's integration test file (which
  runs every ignored test in that file). A workflow qualifies when it triggers on schedule, push or
  pull_request, and the job is not `if: false` or gated on a manual `inputs.` value;
- listed in tools/ignored-tests.toml as `[[allow]]` with `path`, `name` and a `reason` that says what
  runs the same work instead, or why nothing does.

The check fails when it finds no ignored test at all (the scan is then broken), when an allow entry
matches no ignored test, and when an attribute mentions `ignore` in a form it cannot classify. A
function generated by a macro (`fn $name`) is listed under the name `$name`. The scan is line based for
workflows: put the `cargo test ... --ignored <name>` command on one line. It does not model a job
reached through `needs`, a matrix or `workflow_call`; such a job needs an allow entry or a plain command.
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIRS = ('crates', 'xtask')
FUNCTION = re.compile(r'\bfn\s+(\$?[A-Za-z_][A-Za-z0-9_]*)')
PENDING = re.compile(r'phase\s+(\d+)\s*:')
IGNORE_WORD = re.compile(r'(?<![A-Za-z0-9_])ignore(?![A-Za-z0-9_])')
STRING = r'r(#*)".*?"\1|"(?:[^"\\]|\\.)*"'
# `ignore = "reason"` or `ignore = r#"reason"#`.
REASON = re.compile(r'ignore\s*=\s*(?:r(#*)"(.*?)"\1|"((?:[^"\\]|\\.)*)")', re.DOTALL)
# How far after an attribute its `fn` may be (other attributes, doc comments, a macro body).
LOOKAHEAD_LINES = 40
TRIGGERS = re.compile(r'\b(schedule|push|pull_request)\b')
JOB = re.compile(r'^  ([A-Za-z0-9_-]+):\s*$')
JOB_IF = re.compile(r'^    if:\s*(.*)$')
RAW_START = re.compile(r'r(#*)"')


def attributes(text):
    """Yield (line, attribute text, end offset) for every `#[...]`, across lines and string literals."""
    i = 0
    n = len(text)
    while True:
        i = text.find('#[', i)
        if i < 0:
            return
        # Not an attribute: `#[` inside a string literal (xtask spells one out) or a comment.
        prefix = text[text.rfind('\n', 0, i) + 1:i]
        if '//' in prefix or text[i - 1:i] in ('"', "'", '\\'):
            i += 2
            continue
        depth = 0
        j = i + 1
        while j < n:
            c = text[j]
            raw = RAW_START.match(text, j) if c == 'r' and not text[j - 1].isalnum() else None
            if raw:
                end = text.find('"' + raw.group(1), raw.end())
                j = n if end < 0 else end + 1 + len(raw.group(1))
                continue
            if c == '"':
                j += 1
                while j < n and text[j] != '"':
                    j += 2 if text[j] == '\\' else 1
            elif c == '[':
                depth += 1
            elif c == ']':
                depth -= 1
                if depth == 0:
                    break
            j += 1
        if depth != 0:
            raise ValueError(f'unterminated attribute at line {text.count(chr(10), 0, i) + 1}')
        yield text.count('\n', 0, i) + 1, text[i:j + 1], j
        i = j + 1


def ignored_tests(text, path):
    """Return (path, function name, reason) for each attribute that contains the word `ignore`."""
    found = []
    for line, attr, end in attributes(text):
        if not IGNORE_WORD.search(re.sub(STRING, '""', attr, flags=re.DOTALL)):
            continue
        if attr.startswith(('#[doc', '#[allow', '#[expect', '#[warn', '#[deny')):
            raise ValueError(f'{path}:{line}: attribute mentions `ignore` in a form this check cannot classify')
        match = REASON.search(attr)
        reason = ''
        if match:
            reason = match.group(2) if match.group(2) is not None else match.group(3)
        following = text[end + 1:].split('\n')[:LOOKAHEAD_LINES]
        name = next((m.group(1) for m in map(FUNCTION.search, following) if m), None)
        if name is None:
            raise ValueError(f'{path}:{line}: ignore attribute with no function within {LOOKAHEAD_LINES} lines')
        found.append((path, name, reason))
    return found


def workflow_commands(text):
    """Lines of one workflow that pass `--ignored`, when the workflow and the job can run unattended."""
    head = text.split('\njobs:', 1)[0]
    if not TRIGGERS.search(re.sub(r'(?m)^\s*#.*$', '', head)):
        return []
    lines = text.split('\n')
    job_if = {}
    job = None
    for line in lines:
        if JOB.match(line):
            job = JOB.match(line).group(1)
        elif JOB_IF.match(line) and job:
            job_if[job] = JOB_IF.match(line).group(1).strip().strip('"\'')
    out = []
    job = None
    for line in lines:
        if JOB.match(line):
            job = JOB.match(line).group(1)
        if '--ignored' not in line or line.lstrip().startswith('#'):
            continue
        condition = job_if.get(job, '')
        if condition in ('false', '${{ false }}') or condition.startswith(('inputs.', '${{ inputs.', 'github.event.inputs')):
            continue
        out.append(line)
    return out


def ignored_commands(workflows):
    """Workflow lines that pass `--ignored` to a test binary and can run without a person."""
    return [line for text in workflows.values() for line in workflow_commands(text)]


def run_by_workflow(path, name, commands):
    stem = Path(path).stem
    in_tests_dir = 'tests' in Path(path).parts
    for line in commands:
        tokens = line.split()
        if name in tokens:
            return True
        # `--test <stem>` selects an integration test file; with `--ignored` it runs every ignored test in it.
        if in_tests_dir and any(a == '--test' and b == stem for a, b in zip(tokens, tokens[1:])):
            return True
    return False


def problems(tests, workflows, allow, pending_phases=()):
    """One message per ignored test that nothing runs and no allow entry explains."""
    commands = ignored_commands(workflows)
    allowed = {}
    found = []
    if not tests:
        found.append('no ignored test found under crates/ and xtask/; the scan is broken')
    for entry in allow:
        key = (entry.get('path'), entry.get('name'))
        reason = entry.get('reason')
        if not all(isinstance(v, str) and v.strip() for v in (*key, reason)):
            found.append(f'tools/ignored-tests.toml: every [[allow]] needs path, name and a reason: {entry!r}')
            continue
        if key in allowed:
            found.append(f'tools/ignored-tests.toml: duplicate entry for {key[0]}::{key[1]}')
        allowed[key] = reason
    seen = set()
    for path, name, reason in tests:
        seen.add((path, name))
        pending = PENDING.match(reason)
        if pending:
            if int(pending.group(1)) in pending_phases:
                continue
            found.append(
                f'{path}: `{name}` is pending for phase {pending.group(1)}, which is not in pending_phases '
                f'in tools/ignored-tests.toml; run the test or list the phase'
            )
            continue
        if run_by_workflow(path, name, commands):
            if (path, name) in allowed:
                found.append(f'tools/ignored-tests.toml: {path}::{name} is run by a workflow; remove its entry')
            continue
        if (path, name) not in allowed:
            found.append(
                f'{path}: ignored test `{name}` is run by no workflow (`--ignored` with its name or '
                f'`--test {Path(path).stem}`) and has no entry in tools/ignored-tests.toml'
            )
    for path, name in sorted(set(allowed) - seen):
        found.append(f'tools/ignored-tests.toml: {path}::{name} matches no ignored test')
    return found


def collect(root):
    tests = []
    for top in SOURCE_DIRS:
        for file in sorted((root / top).rglob('*.rs')):
            if 'target' in file.relative_to(root).parts:
                continue
            tests.extend(ignored_tests(file.read_text(), file.relative_to(root).as_posix()))
    return tests


def main():
    workflows = {p.name: p.read_text() for p in sorted((ROOT / '.github/workflows').glob('*.yml'))}
    config = tomllib.loads((ROOT / 'tools/ignored-tests.toml').read_text())
    tests = collect(ROOT)
    found = problems(tests, workflows, config.get('allow', []), config.get('pending_phases', []))
    for message in found:
        print(message, file=sys.stderr)
    if found:
        return 1
    print(f'all {len(tests)} ignored tests are pending specifications, run by a workflow or listed with a reason')
    return 0


if __name__ == '__main__':
    sys.exit(main())
