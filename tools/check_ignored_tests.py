#!/usr/bin/env python3
"""Fail when an `#[ignore]` test is neither run by a workflow nor listed with a reason.

An ignored test never runs in `cargo test`, so a volume test that no workflow starts with `--ignored`
is dead code that reads like evidence (#455). Each `#[ignore]` under crates/ and xtask/ must be one of:

- a pending specification: the ignore reason starts with `phase N:` (xtask lists those);
- run by a workflow: some non-comment line of a workflow file under .github/workflows contains
  `--ignored` and either the test function name, or `--test <file stem>` for the test's integration
  test file (which runs every ignored test in that file);
- listed in tools/ignored-tests.toml as `[[allow]]` with `path`, `name` and a `reason` that says what
  runs the same work instead, or why nothing does.

An allow entry that matches no ignored test is also an error, so the list cannot go stale. A function
generated by a macro (`fn $name`) is listed under the name `$name`. The check is line based: put the
`cargo test ... --ignored <name>` command on one line.
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIRS = ('crates', 'xtask')
IGNORE = re.compile(r'#\[ignore(?:\s*=\s*"((?:[^"\\]|\\.)*)")?\s*\]')
FUNCTION = re.compile(r'\bfn\s+(\$?[A-Za-z_][A-Za-z0-9_]*)')
PENDING = re.compile(r'phase\s+\d+\s*:')
# How far after an attribute its `fn` may be (other attributes, doc comments).
LOOKAHEAD_LINES = 6


def ignored_tests(text, path):
    """Return (path, function name, reason) for each `#[ignore]` in one Rust file."""
    found = []
    lines = text.split('\n')
    for number, line in enumerate(lines):
        match = IGNORE.search(line)
        if not match or line.lstrip().startswith('//'):
            continue
        name = None
        for follower in lines[number:number + LOOKAHEAD_LINES]:
            fn = FUNCTION.search(follower)
            if fn:
                name = fn.group(1)
                break
        if name is None:
            raise ValueError(f'{path}:{number + 1}: `#[ignore]` with no function within {LOOKAHEAD_LINES} lines')
        found.append((path, name, match.group(1) or ''))
    return found


def ignored_commands(workflows):
    """Non-comment workflow lines that pass `--ignored` to a test binary."""
    return [
        line for text in workflows.values() for line in text.split('\n')
        if '--ignored' in line and not line.lstrip().startswith('#')
    ]


def run_by_workflow(path, name, commands):
    stem = Path(path).stem
    in_tests_dir = 'tests' in Path(path).parts
    for line in commands:
        tokens = line.split()
        if name in tokens:
            return True
        # `--test <stem>` selects an integration test file; with `--ignored` it runs every ignored test in it.
        if in_tests_dir and any(a == '--test' and b == stem for a, b in zip(tokens, tokens[1:])):
            return True
    return False


def problems(tests, workflows, allow):
    """One message per ignored test that nothing runs and no allow entry explains."""
    commands = ignored_commands(workflows)
    allowed = {}
    found = []
    for entry in allow:
        key = (entry.get('path'), entry.get('name'))
        reason = entry.get('reason')
        if not all(isinstance(v, str) and v.strip() for v in (*key, reason)):
            found.append(f'tools/ignored-tests.toml: every [[allow]] needs path, name and a reason: {entry!r}')
            continue
        if key in allowed:
            found.append(f'tools/ignored-tests.toml: duplicate entry for {key[0]}::{key[1]}')
        allowed[key] = reason
    seen = set()
    for path, name, reason in tests:
        seen.add((path, name))
        if PENDING.match(reason):
            continue
        if run_by_workflow(path, name, commands):
            if (path, name) in allowed:
                found.append(f'tools/ignored-tests.toml: {path}::{name} is run by a workflow; remove its entry')
            continue
        if (path, name) not in allowed:
            found.append(
                f'{path}: ignored test `{name}` is run by no workflow (`--ignored` with its name or '
                f'`--test {Path(path).stem}`) and has no entry in tools/ignored-tests.toml'
            )
    for path, name in sorted(set(allowed) - seen):
        found.append(f'tools/ignored-tests.toml: {path}::{name} matches no ignored test')
    return found


def collect(root):
    tests = []
    for top in SOURCE_DIRS:
        for file in sorted((root / top).rglob('*.rs')):
            if 'target' in file.relative_to(root).parts:
                continue
            tests.extend(ignored_tests(file.read_text(), file.relative_to(root).as_posix()))
    return tests


def main():
    workflows = {p.name: p.read_text() for p in sorted((ROOT / '.github/workflows').glob('*.yml'))}
    allow = tomllib.loads((ROOT / 'tools/ignored-tests.toml').read_text()).get('allow', [])
    tests = collect(ROOT)
    found = problems(tests, workflows, allow)
    for message in found:
        print(message, file=sys.stderr)
    if found:
        return 1
    print(f'all {len(tests)} ignored tests are pending specifications, run by a workflow or listed with a reason')
    return 0


if __name__ == '__main__':
    sys.exit(main())
