fn division_scales_match_postgresql() {
    let mut f = fixture();
    let mut s = admin();
    for (sql, expected) in CASES {
        assert_eq!(
            rows(&mut f.db, &mut s, sql),
            vec![vec![expected.to_string()]],
            "{sql}"
        );
    }
}
